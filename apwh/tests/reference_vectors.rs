fn fixed_session() -> SrpSession {
    SrpSession::resume_handshake(
        Encoding::Base64,
        USERNAME.to_string(),
        crypto::from_bytes_be(&hex::decode(CLIENT_PRIVATE_HEX).unwrap()),
        crypto::from_bytes_be(&server_public_bytes()),
        crypto::from_bytes_be(&hex::decode(SALT_HEX).unwrap()),
    )
}

#[test]
fn client_public_key_matches_the_reference() {
    let session = fixed_session();
    assert_eq!(
        hex::encode(crypto::to_bytes_be(&session.client_public())),
        CLIENT_PUBLIC_HEX
    );
}

#[test]
fn shared_key_matches_the_reference() {
    let mut session = fixed_session();
    let shared_key = session.derive_shared_key(PIN).unwrap();
    assert_eq!(
        hex::encode(crypto::to_bytes_be(&shared_key)),
        SHARED_KEY_HEX
    );
}

#[test]
fn client_proof_and_server_proof_match_the_reference() {
    let mut session = fixed_session();
    session.derive_shared_key(PIN).unwrap();

    let m = session.compute_m().unwrap();
    assert_eq!(hex::encode(m), M_HEX);
    assert_eq!(hex::encode(session.compute_hamk(&m).unwrap()), HAMK_HEX);
}

#[test]
fn aes_key_matches_the_reference() {
    let mut session = fixed_session();
    let shared_key = session.derive_shared_key(PIN).unwrap();
    assert_eq!(
        hex::encode(crypto::aes_key(&shared_key).unwrap().as_slice()),
        AES_KEY_HEX
    );
}

#[test]
fn sealing_reproduces_the_reference_ciphertext_with_the_iv_appended() {
    let key = SecretBytes::new(hex::decode(AES_KEY_HEX).unwrap());
    let iv = hex::decode(IV_HEX).unwrap();
    let sealed = crypto::seal_with_iv(&key, PLAINTEXT.as_bytes(), &iv).unwrap();
    assert_eq!(hex::encode(sealed), REQUEST_SHAPED_HEX);
}

#[test]
fn opening_reads_the_reference_payload_with_the_iv_prefixed() {
    let key = SecretBytes::new(hex::decode(AES_KEY_HEX).unwrap());
    let opened = crypto::open(&key, &hex::decode(RESPONSE_SHAPED_HEX).unwrap()).unwrap();
    assert_eq!(String::from_utf8(opened).unwrap(), PLAINTEXT);
}

#[test]
fn a_session_seals_what_the_reference_key_can_open() {
    let mut session = fixed_session();
    session.derive_shared_key(PIN).unwrap();

    // Sealed through the session, opened with the reference AES key, after
    // moving the IV from tail to head the way the helper does.
    let sealed = session.seal(&serde_json::json!({ "ACT": 5 })).unwrap();
    let (body, iv) = sealed.split_at(sealed.len() - 16);
    let mut response = iv.to_vec();
    response.extend_from_slice(body);

    let key = SecretBytes::new(hex::decode(AES_KEY_HEX).unwrap());
    assert_eq!(crypto::open(&key, &response).unwrap(), br#"{"ACT":5}"#);
}

#[test]
fn a_wrong_pin_produces_a_different_key() {
    let mut session = fixed_session();
    let shared_key = session.derive_shared_key("482916").unwrap();
    assert_ne!(
        hex::encode(crypto::to_bytes_be(&shared_key)),
        SHARED_KEY_HEX
    );
}

#[test]
fn seal_rejects_a_wrong_length_iv() {
    let key = SecretBytes::new(hex::decode(AES_KEY_HEX).unwrap());
    assert!(crypto::seal_with_iv(&key, b"x", &[0u8; 12]).is_err());
}
