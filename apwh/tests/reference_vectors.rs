//! Byte-level parity with the reference implementation.
//!
//! These vectors were produced by running `apw`'s own `src/srp.ts` under Node
//! with fixed inputs (identity, PIN, `a`, `B`, `s`, and a fixed AES-GCM IV), then
//! recording every intermediate value. If a hash input is padded where it should
//! be minimal, or an IV lands on the wrong end of a payload, one of these fails.
//!
//! The oracle script also asserted two things about the reference itself, which
//! is why this file encodes an asymmetric framing:
//!
//! * `apw`'s `decrypt()` reads `iv || ciphertext || tag`.
//! * `apw`'s `encrypt()` emits `ciphertext || tag || iv`.

